// --- Helper utility functions ---

/**
 * Find a station by its unique ID (e.g., "jurong-east").
 */
export function getStationById(id: string): MapStation | undefined {
  return STATIONS.find((s) => s.id === id);
}

/**
 * Find a station by any of its station codes (e.g., "NS1", "EW24").
 */
export function getStationByCode(code: string): MapStation | undefined {
  return STATIONS.find((s) => s.codes.includes(code));
}

/**
 * Get all interchange stations (stations serving multiple lines).
 */
export function getInterchangeStations(): MapStation[] {
  return STATIONS.filter((s) => s.interchange);
}

/**
 * Get all stations on a specific line (e.g., "NS", "EW", "CC").
 */
export function getStationsByLine(line: string): MapStation[] {
  return STATIONS.filter((s) => s.lines.includes(line));
}
